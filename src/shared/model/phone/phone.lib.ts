/**
 * Приводит телефон к E.164.
 *
 * Ведущий `+` — авторитетный признак: он означает «код страны уже
 * указан», и тогда цифры берутся как есть. Без него включаются
 * догадки под российский план нумерации.
 *
 * 8 (999) 123-45-67 -> +79991234567
 * 9991234567        -> +79991234567
 * +7 999 123 45 67  -> +79991234567
 * +7999123456       -> +7999123456   (недобор: не достраиваем, пусть
 *                                     схема сообщит о некорректности)
 */
export function normalizePhone (raw: string): string {
  const digits = raw.replace(/\D/g, '')

  if (!digits) {
    return ''
  }

  // Код страны задан явно — никаких эвристик. Иначе `+7999123456`
  // попадал в ветку «10 цифр = номер без кода» и получал вторую
  // семёрку: `+77999123456`. Это существующий казахстанский префикс,
  // поэтому подмена проходила любую валидацию незамеченной.
  if (raw.trimStart().startsWith('+')) {
    return `+${digits}`
  }

  if (digits.length === 11 && digits.startsWith('8')) {
    return `+7${digits.slice(1)}`
  }

  if (digits.length === 11 && digits.startsWith('7')) {
    return `+${digits}`
  }

  if (digits.length === 10) {
    return `+7${digits}`
  }

  return `+${digits}`
}
